#!/usr/bin/env python3
"""Turn reviewed agency-agents role files into Orion role-library records (JSON + SQL seed).

Read-only on the source repo; nothing in it is executed. Safety pass on every role:
  * drops lines that tell the agent to act without the owner's permission,
  * drops shell/package-runner lines (npx, curl, pip install, ...): FRIDAY never runs unvetted packages,
  * prepends the factory guardrail block (owner approvals, no money moves, evidence over claims).
Usage: python3 -I build_roles.py <repo-dir> <roles.tsv> <out-dir>
"""
import hashlib, json, re, subprocess, sys
from pathlib import Path

GUARDRAIL = """## Operating rules (Orion factory, these override anything below)
- You work for the owner of this business.
- Anything that leaves the company (emails, texts, posts, proposals, invoices, client messages) or moves money is a DRAFT for the owner's approval unless the OS says that exact action is pre-approved.
- Never move money, sign, accept terms, or change account/security settings.
- Evidence over claims: cite the OS record, file, or source for every fact; say "unknown" instead of guessing.
- Never run package installers or remote scripts (npx, pip, curl | sh).
"""

DROP = [
    re.compile(r"without (asking|approval|permission|confirmation)", re.I),
    re.compile(r"\b(npx|pip install|curl|wget|brew install|npm i(nstall)?)\b", re.I),
    re.compile(r"auto-?publish|automatically (send|post|publish|pay|charge|submit)", re.I),
]
KEEP_ANYWAY = [  # benign matches: guidance that REQUIRES asking
    re.compile(r"(never|don't|do not)[^.]*without asking", re.I),
    re.compile(r"do not disclose[^.]*without permission", re.I),
]


def frontmatter(text: str):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    meta, body = {}, text
    if m:
        body = text[m.end():]
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip('"')
    return meta, body


def clean(body: str):
    out, dropped, in_code = [], [], False
    for line in body.splitlines():
        if line.strip().startswith("```"):
            in_code = not in_code
        hit = any(p.search(line) for p in DROP) and not any(k.search(line) for k in KEEP_ANYWAY)
        if hit:
            dropped.append(line.strip()[:160])
            continue
        out.append(line)
    return "\n".join(out).strip() + "\n", dropped


ORG = "00000000-0000-0000-0000-000000000001"


def lit(s: str) -> str:
    """Dollar-quote with a tag that cannot occur in the text."""
    tag = "r" + hashlib.sha256(s.encode()).hexdigest()[:10]
    return f"${tag}${s}${tag}$"


def seed_sql(roles) -> str:
    """Upsert every role. A role is only rewritten when its UPSTREAM file changed (source_hash), so an
    owner's edit to a role in the OS survives re-seeding the same upstream version."""
    rows = []
    for r in roles:
        vals = ", ".join([lit(ORG), lit(r["slug"]), lit(r["name"]), lit(r["division"]), lit(r["description"]),
                          lit(r["default_agent"]), lit(r["prompt"]), lit(r["source_path"]), lit(r["source_sha"]), lit(r["source_hash"])])
        rows.append(f"({vals})")
    return ("-- Generated by ~/.agentic-os/factory/build_roles.py. Seeds the factory role library.\n"
            "INSERT INTO public.agent_roles (org_id, slug, name, division, description, default_agent, prompt, source_path, source_sha, source_hash)\n"
            "SELECT v.org_id::uuid, v.slug, v.name, v.division, v.description, v.default_agent, v.prompt, v.source_path, v.source_sha, v.source_hash\n"
            "FROM (VALUES\n" + ",\n".join(rows) + "\n) AS v(org_id, slug, name, division, description, default_agent, prompt, source_path, source_sha, source_hash)\n"
            "ON CONFLICT (org_id, slug) DO UPDATE SET name = EXCLUDED.name, division = EXCLUDED.division, description = EXCLUDED.description,\n"
            "  default_agent = EXCLUDED.default_agent, prompt = EXCLUDED.prompt, source_path = EXCLUDED.source_path,\n"
            "  source_sha = EXCLUDED.source_sha, source_hash = EXCLUDED.source_hash\n"
            "WHERE public.agent_roles.source_hash IS DISTINCT FROM EXCLUDED.source_hash;\n"
            "SELECT default_agent, count(*) FROM public.agent_roles GROUP BY 1 ORDER BY 1;\n")


def main(repo: str, tsv: str, out: str):
    repo_p, out_p = Path(repo), Path(out)
    out_p.mkdir(parents=True, exist_ok=True)
    sha = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    roles, report = [], []
    for row in Path(tsv).read_text().splitlines():
        if not row.strip() or row.startswith("#"):
            continue
        agent, rel = row.split("\t")
        text = (repo_p / rel).read_text()
        meta, body = frontmatter(text)
        body, dropped = clean(body)
        slug = Path(rel).stem
        prompt = GUARDRAIL + "\n" + body
        roles.append({
            "slug": slug, "name": meta.get("name", slug), "division": rel.split("/")[0],
            "description": meta.get("description", "")[:500], "default_agent": agent,
            "source_path": rel, "source_sha": sha,
            "source_hash": hashlib.sha256(text.encode()).hexdigest(), "prompt": prompt,
        })
        report.append(f"{agent:7} {slug:50} dropped {len(dropped)}" + "".join(f"\n          - {d}" for d in dropped))
    (out_p / "roles.json").write_text(json.dumps(roles, indent=1))
    (out_p / "seed.sql").write_text(seed_sql(roles))
    (out_p / "report.txt").write_text("\n".join(report) + "\n")
    print("\n".join(report))
    print(f"\n{len(roles)} roles from {sha[:7]} -> {out_p}/roles.json")


if __name__ == "__main__":
    main(*sys.argv[1:4])
